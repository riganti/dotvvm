using System.IO;
using CheckTestOutput;
using DotVVM.Framework.Binding;
using DotVVM.Framework.Compilation.ControlTree;
using DotVVM.Framework.Controls;
using DotVVM.Framework.Testing;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace DotVVM.Framework.Tests.ControlTests
{
    [TestClass]
    public class JsComponentTests
    {
        static readonly ControlTestHelper cth = new ControlTestHelper();
        static readonly BindingCompilationService bindingService = cth.GetService<BindingCompilationService>();
        readonly OutputChecker check = new OutputChecker("testoutputs");

        [TestMethod]
        public void Wrapper_HtmlCapability()
        {
            var dataContext = DataContextStack.Create(typeof(string));
            var binding = bindingService.Cache.CreateResourceBinding<string>("_this", dataContext);
            var component = new JsComponent("test") {
                HtmlCapability = new HtmlCapability {
                    ID = new ValueOrBinding<string>("field"),
                    Attributes = { ["title"] = new ValueOrBinding<object>(binding) }
                }
            };
            var valueBoundComponent = new JsComponent("test") {
                HtmlCapability = new HtmlCapability {
                    ID = new ValueOrBinding<string>("valueField"),
                    Attributes = { ["title"] = new ValueOrBinding<object>(bindingService.Cache.CreateValueBinding<string>("_this", dataContext)) }
                }
            };

            var container = new PlaceHolder {
                ID = "container",
                ClientIDMode = ClientIDMode.AutoGenerated,
                Children = { component, new Literal("\n") { RenderSpanElement = false }, valueBoundComponent }
            };
            container.SetValue(Internal.IsNamingContainerProperty, true);

            var html = RenderToString(container);

            check.CheckString(html, fileExtension: "html");
        }

        static string RenderToString(DotvvmControl control)
        {
            var context = DotvvmTestHelper.CreateContext(cth.Configuration);
            control.SetValue(Internal.RequestContextProperty, context);
            control.DataContext = "test title";
            using var output = new StringWriter();
            control.Render(new HtmlWriter(output, context), context);
            return output.ToString();
        }
    }
}
